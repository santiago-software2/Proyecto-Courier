    private void btnPrevisualizarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnPrevisualizarActionPerformed
        // TODO add your handling code here:
        String fechaInicio = txtFechaInicio.getText();
        String fechaFin = txtFechaFin.getText();
        String tipoEnvio = (String) cmbTipoEnvio.getSelectedItem();

        int indiceRemitente = cmbRemitente.getSelectedIndex();
        int idRemitente;
        if (indiceRemitente == 0) {
            idRemitente = 0; // "Todos" está en el índice 0
        } else {
            Object[] fila = listaRemitentes.get(indiceRemitente - 1); // -1 porque "Todos" ocupa el primer lugar
            idRemitente = (int) fila[0];
        }

        GuiaEnvioControlador controlador = new GuiaEnvioControlador();
        System.out.println("DEBUG -> fechaInicio: " + fechaInicio + " | fechaFin: " + fechaFin + " | idRemitente: " + idRemitente + " | tipoEnvio: " + tipoEnvio);
        listaActual = controlador.obtenerDatosReporteSP(fechaInicio, fechaFin, idRemitente, tipoEnvio);

        modelo.setRowCount(0);
        for (Object[] fila : listaActual) {
            modelo.addRow(fila);
        }
        generarGrafico(listaActual);
    }//GEN-LAST:event_btnPrevisualizarActionPerformed

    private void btnGenerarPDFActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnGenerarPDFActionPerformed
        // TODO add your handling code here:
        if (modelo.getRowCount() == 0) {
            JOptionPane.showMessageDialog(null, "Primero previsualice el reporte");
            return;
        }

        javax.swing.JFileChooser selector = new javax.swing.JFileChooser();
        selector.setSelectedFile(new java.io.File("reporte_envios.pdf"));
        int seleccion = selector.showSaveDialog(this);

        if (seleccion == javax.swing.JFileChooser.APPROVE_OPTION) {
            String ruta = selector.getSelectedFile().getAbsolutePath();

            GuiaEnvioControlador controlador = new GuiaEnvioControlador();
            controlador.generarReportePDF(listaActual, graficoActual, ruta);

            JOptionPane.showMessageDialog(null, "Reporte PDF generado correctamente");
        }
    }//GEN-LAST:event_btnGenerarPDFActionPerformed

    /**
     * @param args the command line arguments
     */
    private void cargarCombos() {
        // Combo de tipo de envío
        cmbTipoEnvio.addItem("Todos");
        cmbTipoEnvio.addItem("Nacional");
        cmbTipoEnvio.addItem("Internacional");

        // Combo de remitentes
        cmbRemitente.addItem("Todos");
        GuiaEnvioControlador controlador = new GuiaEnvioControlador();
        listaRemitentes = controlador.listarRemitentes();

        for (Object[] fila : listaRemitentes) {
            cmbRemitente.addItem((String) fila[1]); // fila[1] = nombre
        }
    }

    private void generarGrafico(ArrayList<Object[]> lista) {
        DefaultCategoryDataset dataset = new DefaultCategoryDataset();
        for (Object[] fila : lista) {
            String tipo = (String) fila[0];
            int cantidad = (int) fila[1];
            dataset.addValue(cantidad, "Cantidad", tipo);
        }

        JFreeChart grafico = ChartFactory.createBarChart(
                "Envíos por Tipo",
                "Tipo de Envío",
                "Cantidad",
                dataset
        );
        graficoActual = grafico;

        ChartPanel panelGrafico = new ChartPanel(grafico);

        pnlGraficoReporte.removeAll();
        pnlGraficoReporte.setLayout(new BorderLayout());
        pnlGraficoReporte.add(panelGrafico, BorderLayout.CENTER);
        pnlGraficoReporte.revalidate();
        pnlGraficoReporte.repaint();
    }

