    /**
     * @param args the command line arguments
     */
    private void cargarGuias() {
        GuiaEnvioControlador controlador = new GuiaEnvioControlador();
        ArrayList<Object[]> lista = controlador.listarGuias();

        modelo.setRowCount(0); // limpia la tabla antes de llenar

        for (Object[] fila : lista) {
            modelo.addRow(fila);
        }
    }

