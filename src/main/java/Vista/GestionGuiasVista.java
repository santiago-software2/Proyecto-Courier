    private void btnActualizarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnActualizarActionPerformed
        // TODO add your handling code here:
        int filaSeleccionada = tblGuiasEnvio.getSelectedRow();

        if (filaSeleccionada == -1) {
            JOptionPane.showMessageDialog(null, "Seleccione una guía de la tabla");
            return;
        }

        int idGe = (int) modelo.getValueAt(filaSeleccionada, 0);
        String nuevoEstado = (String) cmbEstado.getSelectedItem();

        GuiaEnvioControlador controlador = new GuiaEnvioControlador();
        boolean exito = controlador.actualizarEstadoGuia(idGe, nuevoEstado);

        if (exito) {
            JOptionPane.showMessageDialog(null, "Estado actualizado correctamente");
            cargarGuias(); // refresca la tabla para ver el cambio
        }
    }//GEN-LAST:event_btnActualizarActionPerformed

